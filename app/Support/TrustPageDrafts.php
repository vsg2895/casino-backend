    {
        $url = 'https://' . $domain;

        return [
            self::about($brand, $url),
            self::howWeRate($brand, $url),
            self::editorialPolicy($brand, $url),
            self::affiliateDisclosure($brand, $url),
            self::responsibleGambling($brand, $url),
            self::contact($brand, $url),
        ];
    }

