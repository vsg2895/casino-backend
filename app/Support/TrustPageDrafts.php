/**
 * First drafts of the six trust pages, for an editor to review before publishing.
 *
 * Written to state only what the platform can stand behind:
 *
 *  - the site is an independent review site, not an operator;
 *  - it earns commission through affiliate links;
 *  - many listed casinos are offshore-licensed, so legality is the reader's to
 *    check where they live;
 *  - the rating is ONE overall 0–5 score set by an editor, informed by the
 *    operator-profile facts the database actually records (casino_details) —
 *    there is no weighted formula, so none is described.
 *
 * No team members, licences, awards, years of experience, phone numbers or
 * addresses are stated. The operator's identity and inboxes are
 * {@see LegalIdentity} tokens, hidden while their setting is empty. Every place
 * that needs a human to confirm a fact carries a visible `TODO:` so it cannot be
 * published by accident without someone noticing; each draft also opens with an
 * HTML comment saying it awaits review.
 *
 * Loaded into the admin by `sites:draft-trust-pages`: as a pending draft beside
 * the live copy for a page that already exists, or as a new `draft` page.
 */
final class TrustPageDrafts
{
    private const string REVIEW_NOTE = '<!-- DRAFT generated by sites:draft-trust-pages — review every statement before publishing. -->';

    /**
     * @return list<array{slug: string, title: string, meta_title: string, meta_description: string, content: string}>
     */
