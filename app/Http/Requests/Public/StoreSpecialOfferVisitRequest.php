<?php

declare(strict_types=1);

namespace App\Http\Requests\Public;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Phase 1 of visit tracking.
 *
 * EVERYTHING HERE IS A CLAIM BY THE PAGE and is sized and typed accordingly.
 * None of it is trusted for anything that matters: the addresses come from the
 * connection, not from this payload, and these fields only ever decorate the
 * record. The limits exist so a hostile poster cannot write a megabyte of
 * `page_url` into the table.
 */
class StoreSpecialOfferVisitRequest extends FormRequest
{
    public function authorize(): bool
    {
        // The site is already authenticated by verify.site; there is no
        // further actor to authorise on a public endpoint.
        return true;
    }

    /**
     * @return array<string, array<int, string>>
     */
    public function rules(): array
    {
        return [
            // Generated by the browser so phase 2 can address this row without
            // us handing out a database id.
            'visit_uuid'      => ['required', 'uuid'],
            'special_offer_id' => ['required', 'integer', 'min:1'],

            'page_url'        => ['nullable', 'string', 'max:2048'],
            'referer'         => ['nullable', 'string', 'max:2048'],

            // IANA zone name — the longest real one is under 64 characters.
            'timezone'        => ['nullable', 'string', 'max:64'],
            // "1920x1080" and similar. Free-form, but bounded.
            'screen'          => ['nullable', 'string', 'max:32'],
            'platform'        => ['nullable', 'string', 'max:64'],

            /*
             * What the visitor answered in the cookie banner. Recorded WITH
             * the row rather than assumed, because the sites promise in
             * writing that nothing is collected without consent, and an
             * auditor's first question is which visits that promise covered.
             */
            'consent'         => ['nullable', 'string', 'in:all,necessary'],
        ];
    }
}
